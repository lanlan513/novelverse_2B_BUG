export function findChapter(chapterId) {
  for (const book of BOOKS) {
    const chapter = book.chapters.find(c => c.id === chapterId)
    if (chapter) return { book, chapter }
  }
  return { book: BOOKS[0], chapter: BOOKS[0].chapters[0] }
}

export function getParagraphs(chapter, editionId) {
  const map = chapter.editions[editionId] || chapter.editions.chengjia
  return map
}

